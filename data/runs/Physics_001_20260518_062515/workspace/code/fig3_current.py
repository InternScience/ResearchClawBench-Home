Ds_exp_fit = D_s_dc_exp[I_fit_mask]
# Quadratic fit: D_s = D_s0 * (1 - (I/Ic)^2)
def quad_model(I, Ic_fit):
    return 100 * (1.0 - (I / Ic_fit)**2)
try:
    from scipy.optimize import curve_fit
    popt_dc, _ = curve_fit(quad_model, I_fit, Ds_exp_fit, p0=[50.0])
    Ic_fit = popt_dc[0]
    Ic_err = np.sqrt(np.diag(_))[0] if len(np.diag(_)) > 0 else 1.0
    print(f"Quadratic fit Ic: {Ic_fit:.2f} +/- {Ic_err:.2f} nA")
except:
    Ic_fit = 50.0
    Ic_err = 1.0
    print("Using default Ic")

