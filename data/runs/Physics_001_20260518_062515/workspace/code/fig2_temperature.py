Tc = 1.0

def power_law_model(T, alpha, Ds0):
    return Ds0 * (1.0 - (T / Tc)**alpha)

mask_sc = (T_arr > 0.05) & (T_arr < Tc) & (D_s_exp_temp > 1.0)
